import fs from "fs";
import path from "path";

import type { IPoolEntry } from "../src/data/duelist-types";
import { DROP_RANKS } from "../src/data/enums";
import { CATALOG_DIR, DATA_DIR, type Catalog, formatIssue, readDataDir, validateData } from "./lib/data";

/**
 * Validates catalog/data and writes src/data/catalog.generated.ts, the module the library reads its
 * data from (spec 03 A-1). Runs before build, typecheck, test and dev. Adding a data file needs no code change.
 * Usage: tsx scripts/build-data.ts [--watch]
 */

const OUT_FILE = path.join(CATALOG_DIR, "src/data/catalog.generated.ts");

/** Pools as [card, weight] pairs, one pool per line: about 12,500 entries, kept small for the site's bundle. */
const renderPools = (catalog: Catalog) => {
    const pairs = (pool: IPoolEntry[]) => JSON.stringify(pool.map(({ card, weight }) => [card, weight]));
    const duelists = catalog.duelists.map(({ id }) => {
        const { deck, drops } = catalog.duelistPools[id];
        const ranks = DROP_RANKS.map((rank) => `            "${rank}": ${pairs(drops[rank])},`).join("\n");
        return `    "${id}": {\n        deck: ${pairs(deck)},\n        drops: {\n${ranks}\n        },\n    },`;
    });
    return `{\n${duelists.join("\n")}\n}`;
};

const render = (catalog: Catalog) => {
    const value = (data: unknown) => JSON.stringify(data, null, 4);
    return `// Generated by catalog/scripts/build-data.ts from catalog/data/**/*.json. Do not edit: run \`yarn data:build\`.
import type { CardId, ICard } from "./card-types";
import type { IDuelist, TDropRank } from "./duelist-types";
import type { ICardImageRef, IEquipCompat, IFieldEffect, IFusion, IImageSource, IRitual } from "./relation-types";
import type { IGameRules } from "./rules";

/** A pool entry as [card, weight]. */
export type PoolPair = [CardId, number];

export const cards: ICard[] = ${value(catalog.cards)};

export const rituals: IRitual[] = ${value(catalog.rituals)};

export const fusions: IFusion[] = ${value(catalog.fusions)};

export const equips: IEquipCompat[] = ${value(catalog.equips)};

export const fields: IFieldEffect[] = ${value(catalog.fields)};

export const images: ICardImageRef[] = ${value(catalog.images)};

export const imageSources: Record<string, IImageSource> = ${value(catalog.imageSources)};

export const duelists: IDuelist[] = ${value(catalog.duelists)};

export const duelistPools: Record<string, { deck: PoolPair[]; drops: Record<TDropRank, PoolPair[]> }> = ${renderPools(catalog)};

export const rules: IGameRules = ${value(catalog.rules)};
`;
};

/** Returns true when the data is valid and the module was written (or already up to date). */
const build = () => {
    const { issues, catalog } = validateData(readDataDir());
    const warnings = issues.filter((issue) => issue.level === "warning").length;
    for (const issue of issues) if (issue.level === "error") console.error(formatIssue(issue));
    if (warnings) console.error(`data:build: ${warnings} warning(s), run \`yarn validate\` to list them`);
    if (!catalog) {
        console.error(`data:build: errors in catalog/data, ${path.relative(CATALOG_DIR, OUT_FILE)} not updated`);
        return false;
    }
    const content = render(catalog);
    const current = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
    if (content !== current) fs.writeFileSync(OUT_FILE, content);
    console.log(
        `data:build: ${catalog.cards.length} cards, ${catalog.rituals.length} rituals, ${catalog.fusions.length} fusions, ${catalog.images.length} images, ${catalog.duelists.length} duelists`,
    );
    return true;
};

if (process.argv.includes("--watch")) {
    build();
    let timer: NodeJS.Timeout | undefined;
    fs.watch(DATA_DIR, { recursive: true }, () => {
        clearTimeout(timer);
        timer = setTimeout(build, 100);
    });
    console.log("data:build: watching catalog/data");
} else if (!build()) {
    process.exit(1);
}
